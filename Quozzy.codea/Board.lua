  end
  saveRerollTune()
end

function rerollTuneReset()
  for _, d in ipairs(rerollTuneDefs) do rerollTune[d.key] = d.def end
  saveRerollTune()
end

-- Auto-reroll countdown: ticked in Main.lua's draw() (STATE_PLAY, solo
-- only); when it reaches zero the board rerolls on its own, whether or
-- not a word was found. Finding a word (WordLogic.lua finalizeWord) also
-- resets it, same as the reroll it triggers. drawBoard() renders it as a
-- shrinking line above the board.
rerollCountdown = rerollCountdown or rerollTune.timerSeconds

-- Mutates the live board for the k-th word THIS player has personally
-- found (k = 1-based count, matching computeRerollPlan's convention).
-- board[r][c] and q.boardTiles are updated in lockstep so they never drift.
-- Board-wide flash, separate from the per-tile rerollAnim table: the
-- background goes to the dice color and fades back to normal once per
-- reroll EVENT (not once per tile), drawn in drawBoard() below. Cleared
-- in generateBoard() so a fresh round never shows a leftover flash.
bgFlashStartTime = bgFlashStartTime or nil

function applyBoardReroll(q, k)
  local n = (q and q.boardSize) or boardSize or 4
  if not (q and q.boardTiles and board) then return end
  local plan = computeRerollPlan(q.seed, n, k)
  for _, idx in ipairs(plan.positions) do
    local r = math.floor((idx - 1) / n) + 1
    local c = ((idx - 1) % n) + 1
    local newLetter = plan.letters[idx]
    q.boardTiles[idx] = newLetter
    board[r][c] = newLetter
    rerollAnim[r] = rerollAnim[r] or {}
    rerollAnim[r][c] = { startTime = ElapsedTime }
  end
  bgFlashStartTime = ElapsedTime
end

function ensureBoardTilesForQMatch(q)
  local size = q.boardSize or boardSize or 4
  
  if areBoardTilesValidForSize(q.boardTiles, size) then
    return q.boardTiles
  end

  local inferred = inferBoardSizeFromTiles(q.boardTiles)
  if inferred and areBoardTilesValidForSize(q.boardTiles, inferred) then
    q.boardSize = inferred
    return q.boardTiles
  end
  
  local tiles = q.seed and generateBoardTilesSeeded(q.seed, size)
    or generateBoardTiles(size, DICE_4x4, DICE_5x5, DICE_6x6)
  q.boardTiles = tiles
  q.boardSize = size
  return tiles
end

function generateBoard(currentQMatch)
    local q = currentQMatch
    local size = (q and q.boardSize) or boardSize or 4
    local tiles = ensureBoardTilesForQMatch(q)
    -- Keep global layout state aligned with the match we are rendering.
    boardSize = size
    buildBoardFromTiles(tiles, size)
    rerollAnim = {}  -- never show a leftover ghost fade from a previous round
    bgFlashStartTime = nil
end

