function getWordListLayout()
    local safeTopY = getTopSafeY()
    local tileSize, startX, startY = computeGridLayout()
    local boardTopY = startY + boardSize * tileSize
    
    -- HUD row is at safeTopY - 32 in drawTopHUD
    local hudTopY = safeTopY - 32

    -- BOTTOM of list area: a bit above the board
    local gapToBoard = 20
    local viewBot = boardTopY + gapToBoard

    -- "words found:" sits 2 row-steps below the HUD (row 1: time/score/size,
    -- row 2: letters/vs, row 3: words found). rowStep = numSize * 1.5.
    local numSize = math.floor(WIDTH * 0.035 + 0.5)
    if numSize < 22 then numSize = 22 end
    if numSize > 28 then numSize = 28 end
    local rowStep = math.floor(numSize * 1.5 + 0.5)
    local labelY = hudTopY - 2 * rowStep

    -- TOP of list area: only ~8px under the label
    local gapLabelToList = 8
    local viewTop = labelY - gapLabelToList
    
    -- height of list viewport
    local viewH = viewTop - viewBot
    if viewH < 60 then viewH = 60 end   -- safety so it never collapses
    
    return labelY, viewTop, viewBot, viewH
end

function isInWordListRegion(x, y)
    local labelY, viewTop, viewBot, viewH = getWordListLayout()
    return x >= sideMargin - 20 and x <= WIDTH * 0.6
    and y >= viewBot and y <= viewTop
end

function shuffle(t)
    for i = #t, 2, -1 do
        local j = math.random(i)
        t[i], t[j] = t[j], t[i]
    end
end

function getTopSafeY()
    if layout and layout.safeArea then
        -- safe area top inset subtracts from HEIGHT
        return HEIGHT - layout.safeArea.top
    else
        return HEIGHT
    end
end

function getBottomSafeY()
    if layout and layout.safeArea then
        return layout.safeArea.bottom
    else
        return 0
    end
end

--####################################################################
-- Ready-Screen Dice Rattle (cosmetic only)
--####################################################################
-- While STATE_READY waits for "tap anywhere to start", the dice show random letters that
-- keep changing, like a handful of dice being shaken. readyRattleLetters is intentionally
-- disconnected from `board` (the real tiles, already generated by generateBoard() before
-- READY ever begins) — whatever's showing at the instant the player taps has NO bearing on
-- the tiles STATE_PLAY reveals a moment later.
readyRattleLetters  = nil  -- readyRattleLetters[r][c]  = the letter currently shown
readyRattleNextFlip = nil  -- readyRattleNextFlip[r][c] = ElapsedTime this cell next changes

function randomDiceLetter(n)
    local dice = (n == 4 and DICE_4x4) or (n == 5 and DICE_5x5) or (n == 6 and DICE_6x6) or DICE_4x4
    local die = dice[math.random(#dice)]
    local faceIndex = math.random(#die)
    local ch = string.upper(die:sub(faceIndex, faceIndex))
    return (ch == "Q") and "Qu" or ch
end

function initReadyRattle(n)
    readyRattleLetters  = {}
    readyRattleNextFlip = {}
    for r = 1, n do
        readyRattleLetters[r]  = {}
        readyRattleNextFlip[r] = {}
        for c = 1, n do
            readyRattleLetters[r][c]  = randomDiceLetter(n)
            readyRattleNextFlip[r][c] = ElapsedTime + math.random() * 0.3  -- stagger the first flip
        end
    end
end

function updateReadyRattle()
    if not readyRattleLetters or #readyRattleLetters ~= boardSize then
        initReadyRattle(boardSize)
        return
    end
    for r = 1, boardSize do
        for c = 1, boardSize do
            if ElapsedTime >= readyRattleNextFlip[r][c] then
                readyRattleLetters[r][c]  = randomDiceLetter(boardSize)
                readyRattleNextFlip[r][c] = ElapsedTime + 0.12 + math.random() * 0.18
            end
        end
    end
end

function generateBoardTiles(n, dice4x4, dice5x5, dice6x6)
    local dice
    if n == 4 then
        dice = dice4x4
    elseif n == 5 then
        dice = dice5x5
    elseif n == 6 then
        dice = dice6x6
    end
    if not dice or #dice < n * n then
        return {}
    end
    local diceCopy = {}
    for i = 1, #dice do diceCopy[i] = dice[i] end
    shuffle(diceCopy)
    
    local tiles = {}
    local idx = 1
    for i = 1, n*n do
        local die = diceCopy[idx]
        idx = idx + 1
        
        local faceIndex = math.random(#die)
        local ch = string.upper(die:sub(faceIndex, faceIndex))
        tiles[i] = (ch == "Q") and "Qu" or ch
    end
    return tiles
end

--####################################################################
-- Seeded reroll primitives (board-reroll-on-word-found feature)
--####################################################################
-- Pure, independent of math.random's global state (shared with menu confetti,
-- dice-rattle, etc. -- must not be entangled, since a reroll needs to be
-- reproducible from (seed,k) alone, regardless of what else called
-- math.random in between). MINSTD Lehmer generator built from only
-- + * % math.floor -- exact on Lua 5.1 through 5.4 and LuaJIT, no bitwise
-- ops, no version assumption.
SEEDED_MODULUS    = 2147483647   -- 2^31 - 1
SEEDED_MULTIPLIER = 48271        -- MINSTD

local function seededHashString(s)
  local h = 5381
  for i = 1, #s do h = (h * 33 + string.byte(s, i)) % SEEDED_MODULUS end
  return h
end

function seededValue(seed, k, salt)
  local function step(a, b)
    local x = (a + b) % SEEDED_MODULUS
    if x == 0 then x = 1 end
    return (x * SEEDED_MULTIPLIER) % SEEDED_MODULUS
  end
  local s  = math.floor(tonumber(seed) or 0) % SEEDED_MODULUS
  local kk = math.floor(tonumber(k) or 0) % SEEDED_MODULUS
  local saltN = (type(salt) == "string") and seededHashString(salt)
             or (math.floor(tonumber(salt) or 0) % SEEDED_MODULUS)
  local x = step(s, 0); x = step(x, kk); x = step(x, saltN)
  return x / SEEDED_MODULUS
end

-- Seeded twin of shuffle(t) (above) -- copies first rather than mutating in
-- place, since callers here always want a fresh array back.
function seededShuffle(seed, k, saltPrefix, t)
  local copy = {}
  for i = 1, #t do copy[i] = t[i] end
  for i = #copy, 2, -1 do
    local j = math.floor(seededValue(seed, k, saltPrefix .. ":" .. i) * i) + 1
    if j > i then j = i end
    copy[i], copy[j] = copy[j], copy[i]
  end
  return copy
end

-- Seeded twin of generateBoardTiles (above). k=0 is reserved for "the
-- initial board" so it never collides with a reroll k (which starts at 1).
function generateBoardTilesSeeded(seed, n)
  local dice = (n == 4 and DICE_4x4) or (n == 5 and DICE_5x5) or (n == 6 and DICE_6x6)
  if not dice or #dice < n * n then return {} end
  local diceCopy = seededShuffle(seed, 0, "initShuffle", dice)
  local tiles = {}
  for i = 1, n * n do
    local die = diceCopy[i]
    local faceIndex = math.floor(seededValue(seed, 0, "initFace" .. i) * #die) + 1
    if faceIndex > #die then faceIndex = #die end
    local ch = string.upper(die:sub(faceIndex, faceIndex))
    tiles[i] = (ch == "Q") and "Qu" or ch
  end
  return tiles
end

-- The k-th reroll (k = the count of words THIS player has personally found
-- so far, 1-based) for an n x n board, as a pure function of (seed, n, k).
-- Both players in a head-to-head match compute the identical plan at the
-- same k, independently, with no data ever crossing the wire for it.
function computeRerollPlan(seed, n, k)
  local total = n * n
  -- Debug-tunable (RipplePicker.lua steppers, rerollTuneDefs below) --
  -- exact percentage, no added randomness, so tuning the slider has a
  -- direct, predictable effect rather than being obscured by a seeded
  -- band. Clamped to [1, total] so it can never ask for zero or more
  -- tiles than exist regardless of how the slider's dragged.
  local percent = (rerollTune and rerollTune.percent) or 30
  local count = math.floor(total * percent / 100 + 0.5)
  if count < 1 then count = 1 end
  if count > total then count = total end

  local allPositions = {}
  for i = 1, total do allPositions[i] = i end
  local shuffled = seededShuffle(seed, k, "rerollPos", allPositions)

  -- Die selection must match generateBoardTilesSeeded's approach: shuffle
  -- the dice bag ONCE and assign one die per tile, no reuse. Independently
  -- sampling a die per tile WITH replacement (the original approach here)
  -- lets a rare die (there's usually only 1-2 Q-dice in the whole set)
  -- get redrawn repeatedly across the many reroll events in a long game,
  -- clustering -- confirmed live: a full 6x6 game produced two entire rows
  -- of "Qu". Shuffling once per reroll event bounds how many Qu a single
  -- event can ever produce to the number of Q-dice in the set, exactly
  -- like the initial board.
  local dice = (n == 4 and DICE_4x4) or (n == 5 and DICE_5x5) or (n == 6 and DICE_6x6)
  local shuffledDice = seededShuffle(seed, k, "rerollDice", dice)

  local positions = {}
  local letters = {}
  for i = 1, count do
    local idx = shuffled[i]
    positions[i] = idx
    local die = shuffledDice[i]
    local faceIndex = math.floor(seededValue(seed, k, "rerollFace" .. idx) * #die) + 1
    if faceIndex > #die then faceIndex = #die end
    local ch = string.upper(die:sub(faceIndex, faceIndex))
    letters[idx] = (ch == "Q") and "Qu" or ch
  end

  return { count = count, positions = positions, letters = letters }
end

function inferBoardSizeFromTiles(tiles)
    if type(tiles) ~= "table" then return nil end
    local len = #tiles
    if len == 16 then return 4 end
    if len == 25 then return 5 end
    if len == 36 then return 6 end
    return nil
end

function areBoardTilesValidForSize(tiles, n)
    if type(tiles) ~= "table" then return false end
    if n ~= 4 and n ~= 5 and n ~= 6 then return false end
    if #tiles ~= n * n then return false end
    for i = 1, #tiles do
        local t = tiles[i]
        if type(t) ~= "string" or t == "" then
            return false
        end
    end
    return true
end

function buildBoardFromTiles(tiles, n)
    board = {}
    tileRects = {}
    
    local idx = 1
    for r = 1, n do
        board[r] = {}
        tileRects[r] = {}
        for c = 1, n do
            board[r][c] = tiles[idx] or "?"
            idx = idx + 1
        end
    end
end

