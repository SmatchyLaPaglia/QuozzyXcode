-- READY-only jitter: each tile wobbles (position) and tilts (rotation) around its own
-- resting spot on an independent phase (seeded from r,c so neighbors don't sync up, and
-- the tilt uses different frequency/phase multipliers than the position wobble so the two
-- don't visually lock into a single simple back-and-forth) — reads as a handful of dice
-- rattling in place. Shared by drawBoard()'s live READY render AND captureBoardSnapAnim()
-- (below), which snapshots each tile's jitter at the instant of tap so the STATE_PLAY
-- snap-in animation starts from wherever the tile actually was, not from zero.
function computeReadyTileJitter(r, c, w)
    local amp = w * 0.045
    local jx = math.sin(ElapsedTime * 9.5 + r * 1.7 + c * 2.3) * amp
    local jy = math.cos(ElapsedTime * 8.3 + r * 2.1 + c * 1.3) * amp
    local angle = math.sin(ElapsedTime * 11.3 + r * 2.9 + c * 1.1) * 7
    return jx, jy, angle
end

-- Called once, right as STATE_READY -> STATE_PLAY (Main.lua touched()), so the tiles snap
-- into place from wherever they were rattling instead of just popping there. Purely a
-- draw-time offset like the jitter itself — tileRects (hit-testing) are untouched.
boardSnapAnim = boardSnapAnim or nil  -- { active, startTime, duration, tiles = {[r]={[c]={jx,jy,angle}}} }
function captureBoardSnapAnim()
    local tileSize = computeGridLayout()
    local tiles = {}
    for r = 1, boardSize do
        tiles[r] = {}
        for c = 1, boardSize do
            local jx, jy, angle = computeReadyTileJitter(r, c, tileSize)
            tiles[r][c] = { jx = jx, jy = jy, angle = angle }
        end
    end
    boardSnapAnim = { active = true, startTime = ElapsedTime, duration = 0.16, tiles = tiles }
end

function drawBoard()
    local tileSize, startX, startY, boardGap, bgSize = computeGridLayout()
    buildTileRects()

    if boardSnapAnim and boardSnapAnim.active and (ElapsedTime - boardSnapAnim.startTime) >= boardSnapAnim.duration then
        boardSnapAnim.active = false
    end

    pushStyle()
    rectMode(CENTER)
    textAlign(CENTER)
    textMode(CENTER)
    font(GLOBAL_UI_FONT_DICE)  -- pinned: dice letters are exempt from GLOBAL_UI_FONT, see Main.lua
    fontSize(tileSize * 0.45)

    -- rounded grid background with higher contrast
    local bgW = bgSize
    local bgH = bgSize
    local bgX = WIDTH/2
    local bgY = startY + (boardSize * tileSize)/2
    
    local bgFill   = Color.gridBg
    local bgStroke = Color.gridBg

    drawRoundedRect(
    bgX, bgY,
    bgW, bgH,
    tileSize * 0.28,     -- corner radius
    bgFill,
    bgStroke
    )

    -- Auto-reroll countdown: a line just above the board that drains from
    -- full width down to nothing: left edge fixed, right edge creeps in.
    -- Solo-only (matches where the countdown actually ticks, Main.lua).
    if state == STATE_PLAY and not useTurnBased and currentQMatch then
        local barH  = tileSize * 0.08
        local barGap = tileSize * 0.12
        local barY  = bgY + bgH / 2 + barGap + barH / 2
        local frac  = math.max(0, math.min(1, (rerollCountdown or rerollTune.timerSeconds) / rerollTune.timerSeconds))
        local barW  = bgW * frac
        local barX  = (bgX - bgW / 2) + barW / 2
        pushStyle()
        rectMode(CENTER)
        noStroke()
        fill(Color.uiAccent or color(40, 80, 60, 255))
        rect(barX, barY, barW, barH)
        popStyle()
    end

    for r = 1, boardSize do
        for c = 1, boardSize do
            local tr = tileRects[r][c]
            local x, y, w, h = tr.x, tr.y, tr.w, tr.h

            local inPath = tileInCurrentPath(r, c)

            local jx, jy, angle = 0, 0, 0
            if state == STATE_READY then
                jx, jy, angle = computeReadyTileJitter(r, c, w)
            elseif state == STATE_PLAY and boardSnapAnim and boardSnapAnim.active then
                -- Snap-in: ease the captured jitter back down to (0,0,0) instead of a hard pop.
                local snap = boardSnapAnim.tiles[r] and boardSnapAnim.tiles[r][c]
                if snap then
                    local remain = 1 - (ElapsedTime - boardSnapAnim.startTime) / boardSnapAnim.duration
                    local ease = remain * remain  -- quadratic ease-out: fast start, gentle settle
                    jx, jy, angle = snap.jx * ease, snap.jy * ease, snap.angle * ease
                end
            end

            -- drawRoundedRect's stroke lines (width 2r) cover the whole tile, so the color that
            -- was ever visible was the STROKE color; keep that as the die color.
            local fillCol   = inPath and Color.selectLineAlsoWeirdlyTileHighlight or Color.tileStroke

            local label
            if state == STATE_READY then
                label = (readyRattleLetters and readyRattleLetters[r] and readyRattleLetters[r][c]) or "?"
            else
                label = board[r][c]
            end

            local letterFill
            if inPath then
                letterFill = Color.tileLetterHighlight
            else
                letterFill = Color.tileLetter or color(255, 255, 255, 255)
            end

            if angle ~= 0 then
                pushMatrix()
                translate(x + jx, y + jy)
                rotate(angle)
                drawDie(0, 0, w * 0.95, h * 0.95, w * 0.25, fillCol, angle)
                popMatrix()
            else
                drawDie(x + jx, y + jy, w * 0.95, h * 0.95, w * 0.25, fillCol, 0)
            end

            -- Letter: a stable, always-visible base at normal size/color,
            -- so the tile is always readable no matter the animation
            -- phase. While a reroll animation is active for this tile, an
            -- overlay pops on top of it, bold: phase 1 grows from normal
            -- to 1.6x while fading color from an eye-catching accent to
            -- normal; phase 2 keeps expanding past that while fading out
            -- entirely, leaving just the stable base behind.
            pushMatrix()
            translate(x + jx, y + jy)
            if angle ~= 0 then rotate(angle) end
            font(GLOBAL_UI_FONT_DICE)
            fill(letterFill)
            text(label, 0, 0)
            popMatrix()

            local ranim = rerollAnim[r] and rerollAnim[r][c]
            if ranim then
                local elapsed = ElapsedTime - ranim.startTime
                local growScale   = rerollTune.growScale
                local growSeconds = rerollTune.growSeconds
                local fadeSeconds = rerollTune.fadeSeconds
                local growBy      = growScale - 1.0  -- phase 2 extends by the same amount again
                local overlayScale, overlayFill
                -- Same bright cyan as the drag-selection line (drawSelectionPath
                -- below) -- always visible regardless of theme, unlike
                -- Color.uiAccent2 which wasn't contrasty enough against the
                -- normal letter color. Held constant (no fade-to-normal-color):
                -- since the overlay fades out entirely in phase 2 anyway, there's
                -- no need to also blend its color toward the letter underneath.
                local accent = color(120, 255, 255, 255)

                if elapsed < growSeconds then
                    local u = elapsed / growSeconds
                    overlayScale = 1.0 + growBy * u  -- normal -> growScale
                    overlayFill = accent
                elseif elapsed < growSeconds + fadeSeconds then
                    local u = (elapsed - growSeconds) / fadeSeconds
                    overlayScale = growScale + growBy * u  -- keeps expanding past growScale
                    overlayFill = color(accent.r, accent.g, accent.b, accent.a * (1 - u))
                else
                    rerollAnim[r][c] = nil
                end

                if overlayScale then
                    pushMatrix()
                    translate(x + jx, y + jy)
                    if angle ~= 0 then rotate(angle) end
                    scale(overlayScale)
                    font("Helvetica-Bold")
                    fill(overlayFill)
                    text(label, 0, 0)
                    popMatrix()
                end
            end
        end
    end

    popStyle()
end

